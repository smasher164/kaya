#!/usr/bin/env python3
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "lib"))
from kaya_gate import ROOT, dev_shell_or_die, scratch_dir

dev_shell_or_die()

# The album covers the network-images scenes fetch (docs/network-images-plan.md
# §5). FFmpeg is the dev shell's; byte-stable with +bitexact and one thread.
#
#   tools/gen-covers.py                  write guests/assets/covers/
#   tools/gen-covers.py --out DIR        write DIR instead
#   tools/gen-covers.py --check [--against DIR]
#                                        regenerate into scratch and compare

import argparse
import subprocess

FAMILY = ROOT / "guests" / "assets" / "covers"

INSIDE = {
    "circle": "lt(hypot(X-W/2,Y-H/2),W*0.3)",
    "square": "lt(abs(X-W/2),W*0.25)*lt(abs(Y-H/2),H*0.25)",
    "diamond": "lt(abs(X-W/2)+abs(Y-H/2),W*0.32)",
}

# name, side, gradient top RGB, gradient bottom RGB, shape
COVERS = [
    ("cover-600.jpg", 600, (0xC8, 0x46, 0x2E), (0x7A, 0x1E, 0x14), "circle"),
    ("cover-320.jpg", 320, (0x2E, 0x6F, 0xC8), (0x14, 0x2F, 0x7A), "square"),
    ("cover-1000.jpg", 1000, (0x2E, 0xA0, 0x5A), (0x0F, 0x4A, 0x2A), "diamond"),
]
SHAPE_RGB = (0xF4, 0xEC, 0xD8)


def channel(i, top, bottom, shape):
    grad = f"{top[i]}+({bottom[i] - top[i]})*Y/H"
    return f"if({INSIDE[shape]},{SHAPE_RGB[i]},{grad})"


def generate(out):
    out.mkdir(parents=True, exist_ok=True)
    for name, side, top, bottom, shape in COVERS:
        geq = ":".join(f"{c}='{channel(i, top, bottom, shape)}'"
                       for i, c in enumerate("rgb"))
        cmd = ["ffmpeg", "-nostdin", "-hide_banner", "-loglevel", "error", "-y",
               "-threads", "1", "-filter_threads", "1",
               "-f", "lavfi", "-i", f"color=c=black:s={side}x{side}:d=1",
               "-vf", f"format=gbrp,geq={geq},format=yuvj420p",
               "-frames:v", "1", "-c:v", "mjpeg", "-q:v", "3",
               "-fflags", "+bitexact", "-flags", "+bitexact",
               "-map_metadata", "-1", str(out / name)]
        r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                           check=False)
        if r.returncode != 0:
            raise SystemExit(f"gen-covers: ffmpeg failed on {name}: {r.stderr.strip()}")


def listing(d):
    return {p.name: p.read_bytes() for p in sorted(d.glob("*.jpg"))}


def compare(fresh, committed):
    a, b = listing(fresh), listing(committed)
    bad = [f"{n}: not generated by tools/gen-covers.py" for n in sorted(set(b) - set(a))]
    bad += [f"{n}: generated but not in {committed}" for n in sorted(set(a) - set(b))]
    bad += [f"{n}: differs from what tools/gen-covers.py generates"
            for n in sorted(set(a) & set(b)) if a[n] != b[n]]
    return bad, len(a)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=pathlib.Path)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--against", type=pathlib.Path, default=FAMILY)
    args = ap.parse_args()
    if args.check:
        with scratch_dir("kaya-gen-covers-") as fresh:
            generate(fresh)
            bad, n = compare(fresh, args.against)
        if bad:
            for b in bad:
                print(f"gen-covers: {b}", file=sys.stderr)
            print(f"gen-covers: FAIL — {len(bad)} of {n} files; regenerate with "
                  f"`tools/gen-covers.py`", file=sys.stderr)
            raise SystemExit(1)
        print(f"gen-covers: OK — {n} files byte-identical to {args.against}")
        return
    out = args.out or FAMILY
    for p in out.glob("*.jpg"):
        p.unlink()
    generate(out)
    for name, data in listing(out).items():
        print(f"gen-covers: wrote {name}, {len(data)} bytes")


main()
