//! C emitter: a header of static inline packers over a caller-owned
//! buffer, plus the occurrence parser. Constants are NOT emitted here —
//! cbindgen already puts KAYA_TX_*/KAYA_KIND_*/... in kaya.h, which this
//! header includes.

use kaya::spec::{FieldTy, ProtocolSpec};

use crate::{Ctx, is_padding, prop_variants, record_params};

/// C keywords plus this header's own identifiers.
pub const RESERVED: &[&str] = &[
    "auto", "break", "case", "char", "const", "continue", "default", "do", "double", "else",
    "enum", "extern", "float", "for", "goto", "if", "inline", "int", "long", "register",
    "restrict", "return", "short", "signed", "sizeof", "static", "struct", "switch", "typedef",
    "union", "unsigned", "void", "volatile", "while",
    // NOT A KEYWORD — a local this generator EMITS, `size_t kaya_at =
    // kaya_wire_begin(...)`, which a spec field of the same name would
    // redeclare in the same scope. swift.rs has the twin.
    "kaya_at",
];

pub fn emit(spec: &ProtocolSpec) -> String {
    let mut c = Ctx { out: String::new() };
    c.line("/* kaya wire vocabulary. Generated by kaya-bindgen from kaya::spec — do not edit.");
    c.line(" *");
    c.line(" * Static inline packers over a caller-owned KayaTx buffer, and the");
    c.line(" * occurrence parser. Records are {u32 size, u16 kind, u16 flags}, body,");
    c.line(" * padded to 8, little-endian; constants come from kaya.h. */");
    c.line("");
    c.line("#ifndef KAYA_WIRE_H");
    c.line("#define KAYA_WIRE_H");
    c.line("");
    c.line("#include <kaya.h>");
    c.line("#include <stdio.h>");
    c.line("#include <string.h>");
    c.line("");
    c.line("/* A transaction under construction: the caller's buffer, how far this");
    c.line(" * transaction has got, and how much there is. THE CALLER SIZES IT and");
    c.line(" * owns the storage; every packer below REFUSES past `cap` rather than");
    c.line(" * writing past it, and past cap `len` goes on counting what the whole");
    c.line(" * transaction WOULD take (snprintf's return), so it is exactly the size");
    c.line(" * to grow to. Submit only what kaya_tx_ok() accepts; the grow-and-retry");
    c.line(" * pattern is in DESIGN.md, Binding conventions. */");
    c.line("typedef struct {");
    c.line("    uint8_t *buf;");
    c.line("    size_t len;");
    c.line("    size_t cap;");
    c.line("} KayaTx;");
    c.line("");
    c.line("/* Did every record fit? A false answer has already said why on stderr. */");
    c.line("static inline int kaya_tx_ok(const KayaTx *tx) {");
    c.line("    return tx->len <= tx->cap;");
    c.line("}");
    c.line("");
    c.line("/* A scalar for keys and values, tagged with a KAYA_VALUE_* type.");
    c.line(" * For parsed strings, s points into the record buffer (not");
    c.line(" * NUL-terminated); s_len is the byte length. */");
    c.line("typedef struct {");
    c.line("    uint32_t type;");
    c.line("    int64_t i;");
    c.line("    double f;");
    c.line("    const char *s;");
    c.line("    uint32_t s_len;");
    c.line("} KayaVal;");
    c.line("");
    c.line("/* One variant of a collection's element sum: its ordered");
    c.line(" * KAYA_VALUE_* field tags. A record collection declares one. */");
    c.line("typedef struct {");
    c.line("    const uint32_t *tags;");
    c.line("    uint32_t len;");
    c.line("} KayaVariantSchema;");
    c.line("");
    c.line("static inline KayaVal kaya_str(const char *s) {");
    c.line("    KayaVal v = {KAYA_VALUE_STR, 0, 0, s, (uint32_t)strlen(s)};");
    c.line("    return v;");
    c.line("}");
    c.line("");
    c.line("static inline KayaVal kaya_i64(int64_t i) {");
    c.line("    KayaVal v = {KAYA_VALUE_I64, i, 0, 0, 0};");
    c.line("    return v;");
    c.line("}");
    c.line("");
    c.line("static inline KayaVal kaya_f64(double f) {");
    c.line("    KayaVal v = {KAYA_VALUE_F64, 0, f, 0, 0};");
    c.line("    return v;");
    c.line("}");
    c.line("");
    c.line("static inline KayaVal kaya_bool(int b) {");
    c.line("    KayaVal v = {KAYA_VALUE_BOOL, b != 0, 0, 0, 0};");
    c.line("    return v;");
    c.line("}");
    c.line("");
    c.line("/* A blob by its kaya_blob_register handle (riding in i), consumed by");
    c.line(" * the next submit; the bytes never enter the record stream. */");
    c.line("static inline KayaVal kaya_blob(uint64_t handle) {");
    c.line("    KayaVal v = {KAYA_VALUE_BLOB, (int64_t)handle, 0, 0, 0};");
    c.line("    return v;");
    c.line("}");
    c.line("");
    c.line("/* Room for n more bytes? Past cap `len` keeps counting, so this stays");
    c.line(" * false for the rest of the transaction — one refusal, not a cascade. */");
    c.line("static inline int kaya_wire_fits(const KayaTx *tx, size_t n) {");
    c.line("    return tx->len <= tx->cap && n <= tx->cap - tx->len;");
    c.line("}");
    c.line("");
    c.line("static inline void kaya_wire_u32(KayaTx *tx, uint32_t v) {");
    c.line("    if (kaya_wire_fits(tx, 4))");
    c.line("        memcpy(tx->buf + tx->len, &v, 4);");
    c.line("    tx->len += 4;");
    c.line("}");
    c.line("");
    c.line("static inline void kaya_wire_u64(KayaTx *tx, uint64_t v) {");
    c.line("    if (kaya_wire_fits(tx, 8))");
    c.line("        memcpy(tx->buf + tx->len, &v, 8);");
    c.line("    tx->len += 8;");
    c.line("}");
    c.line("");
    c.line("static inline void kaya_wire_pad(KayaTx *tx) {");
    c.line("    while (tx->len % 8 != 0) {");
    c.line("        if (kaya_wire_fits(tx, 1))");
    c.line("            tx->buf[tx->len] = 0;");
    c.line("        tx->len++;");
    c.line("    }");
    c.line("}");
    c.line("");
    c.line("/* Values are self-padded to 8: they concatenate inside bodies. */");
    c.line("static inline void kaya_wire_value(KayaTx *tx, KayaVal v) {");
    c.line("    kaya_wire_u32(tx, v.type);");
    c.line("    switch (v.type) {");
    c.line("    case KAYA_VALUE_BOOL:");
    c.line("        kaya_wire_u32(tx, 1);");
    c.line("        if (kaya_wire_fits(tx, 1))");
    c.line("            tx->buf[tx->len] = (uint8_t)v.i;");
    c.line("        tx->len += 1;");
    c.line("        break;");
    c.line("    case KAYA_VALUE_I64:");
    c.line("    case KAYA_VALUE_BLOB: /* the u64 handle rides in i */");
    c.line("        kaya_wire_u32(tx, 8);");
    c.line("        if (kaya_wire_fits(tx, 8))");
    c.line("            memcpy(tx->buf + tx->len, &v.i, 8);");
    c.line("        tx->len += 8;");
    c.line("        break;");
    c.line("    case KAYA_VALUE_F64:");
    c.line("        kaya_wire_u32(tx, 8);");
    c.line("        if (kaya_wire_fits(tx, 8))");
    c.line("            memcpy(tx->buf + tx->len, &v.f, 8);");
    c.line("        tx->len += 8;");
    c.line("        break;");
    c.line("    default:");
    c.line("        kaya_wire_u32(tx, v.s_len);");
    c.line("        if (kaya_wire_fits(tx, v.s_len))");
    c.line("            memcpy(tx->buf + tx->len, v.s, v.s_len);");
    c.line("        tx->len += v.s_len;");
    c.line("    }");
    c.line("    kaya_wire_pad(tx);");
    c.line("}");
    c.line("");
    c.line("/* A counted value sequence — a key path or a record: {u32 count,");
    c.line(" * u32 reserved, count values}. */");
    c.line("static inline void kaya_wire_values(KayaTx *tx, const KayaVal *vals, uint32_t n) {");
    c.line("    kaya_wire_u32(tx, n);");
    c.line("    kaya_wire_u32(tx, 0);");
    c.line("    for (uint32_t i = 0; i < n; i++)");
    c.line("        kaya_wire_value(tx, vals[i]);");
    c.line("}");
    c.line("");
    c.line("/* A collection schema: {u32 count, u32 reserved, count KAYA_VALUE_*");
    c.line(" * tags}, padded to 8. */");
    c.line("static inline void kaya_wire_variant_schemas(KayaTx *tx, const KayaVariantSchema *variants, uint32_t n) {");
    c.line("    kaya_wire_u32(tx, n);");
    c.line("    kaya_wire_u32(tx, 0);");
    c.line("    for (uint32_t i = 0; i < n; i++) {");
    c.line("        kaya_wire_u32(tx, variants[i].len);");
    c.line("        for (uint32_t j = 0; j < variants[i].len; j++)");
    c.line("            kaya_wire_u32(tx, variants[i].tags[j]);");
    c.line("    }");
    c.line("    kaya_wire_pad(tx);");
    c.line("}");
    c.line("");
    c.line("static inline size_t kaya_wire_begin(KayaTx *tx, uint16_t kind) {");
    c.line("    size_t start = tx->len;");
    c.line("    if (kaya_wire_fits(tx, 8)) {");
    c.line("        memset(tx->buf + tx->len, 0, 8);");
    c.line("        memcpy(tx->buf + tx->len + 4, &kind, 2);");
    c.line("    }");
    c.line("    tx->len += 8;");
    c.line("    return start;");
    c.line("}");
    c.line("");
    c.line("/* The refusal, said once — for the FIRST record that did not fit, since");
    c.line(" * after it every later record starts past cap. The kind is read back");
    c.line(" * out of the header this record wrote; when even those 8 bytes were");
    c.line(" * past cap nothing recorded it, and the second sentence says so rather");
    c.line(" * than naming a kind it never saw. */");
    c.line("static inline void kaya_wire_refused(const KayaTx *tx, size_t start) {");
    c.line("    if (8 <= tx->cap - start) {");
    c.line("        uint16_t kind = 0;");
    c.line("        memcpy(&kind, tx->buf + start + 4, 2);");
    c.line("        fprintf(stderr,");
    c.line("                \"kaya: transaction full — record kind %u needs %zu bytes \"");
    c.line("                \"and this caller sized %zu; nothing past cap was written, \"");
    c.line("                \"so grow to tx.len when this build ends and build it \"");
    c.line("                \"again\\n\",");
    c.line("                (unsigned)kind, tx->len, tx->cap);");
    c.line("    } else {");
    c.line("        fprintf(stderr,");
    c.line("                \"kaya: transaction full — a record starting at byte %zu \"");
    c.line("                \"needs %zu bytes and this caller sized %zu; its 8-byte \"");
    c.line("                \"header was itself past cap, so nothing recorded its kind \"");
    c.line("                \"and this sentence cannot name it\\n\",");
    c.line("                start, tx->len, tx->cap);");
    c.line("    }");
    c.line("}");
    c.line("");
    c.line("static inline void kaya_wire_end(KayaTx *tx, size_t start) {");
    c.line("    kaya_wire_pad(tx);");
    c.line("    if (tx->len <= tx->cap) {");
    c.line("        uint32_t size = (uint32_t)(tx->len - start);");
    c.line("        memcpy(tx->buf + start, &size, 4);");
    c.line("    } else if (start <= tx->cap) {");
    c.line("        kaya_wire_refused(tx, start);");
    c.line("    }");
    c.line("}");

    c.line(&format!("/* KAYA_SPEC_HASH: {}. */", "the protocol fingerprint; the runtime asserts the loaded core agrees"));
    c.line(&format!("#define KAYA_SPEC_HASH 0x{:016x}ULL", crate::spec_hash()));
    c.line("");
    for r in spec.tx {
        if r.name == "set_property" {
            continue;
        }
        let params = record_params(r);
        let mut sig: Vec<String> = vec!["KayaTx *tx".into()];
        for f in &params {
            sig.push(match f.ty {
                FieldTy::U32 => format!("uint32_t {}", f.name),
                FieldTy::U64 => format!("uint64_t {}", f.name),
                FieldTy::Value => format!("KayaVal {}", f.name),
                FieldTy::Values => format!("const KayaVal *{}, uint32_t {}_len", f.name, f.name),
                FieldTy::VariantSchemas => {
                    format!("const KayaVariantSchema *{}, uint32_t {}_len", f.name, f.name)
                }
            });
        }
        c.line("");
        c.line(&format!("/* {} */", r.doc.replace('\n', " ")));
        c.line(&format!(
            "static inline void kaya_tx_{}({}) {{",
            r.name,
            sig.join(", ")
        ));
        c.line(&format!(
            "    size_t kaya_at = kaya_wire_begin(tx, KAYA_TX_{});",
            r.name.to_uppercase()
        ));
        for f in r.fields {
            c.line(&match f.ty {
                FieldTy::U32 if is_padding(f) => "    kaya_wire_u32(tx, 0);".into(),
                FieldTy::U32 => format!("    kaya_wire_u32(tx, {});", f.name),
                FieldTy::U64 => format!("    kaya_wire_u64(tx, {});", f.name),
                FieldTy::Value => format!("    kaya_wire_value(tx, {});", f.name),
                FieldTy::Values => {
                    format!("    kaya_wire_values(tx, {}, {}_len);", f.name, f.name)
                }
                FieldTy::VariantSchemas => {
                    format!("    kaya_wire_variant_schemas(tx, {}, {}_len);", f.name, f.name)
                }
            });
        }
        c.line("    kaya_wire_end(tx, kaya_at);");
        c.line("}");
    }

    for (prop, _, kind) in prop_variants(spec) {
        let up = prop.to_uppercase();
        // Blob setters take the u64 kaya_blob_register handle.
        let (ty, ctor, param) = match kind {
            crate::PropKind::Str => ("const char *", "kaya_str", *prop),
            crate::PropKind::Bool => ("int ", "kaya_bool", *prop),
            crate::PropKind::F64 => ("double ", "kaya_f64", *prop),
            crate::PropKind::Blob => ("uint64_t ", "kaya_blob", "handle"),
            crate::PropKind::Enum(_) => ("int64_t ", "kaya_i64", *prop),
        };
        c.line("");
        c.line(&format!("/* set_property with a constant {prop} value. */"));
        c.line(&format!("static inline void kaya_tx_set_{prop}(KayaTx *tx, uint64_t widget_id, {ty}{param}) {{"));
        c.line("    size_t kaya_at = kaya_wire_begin(tx, KAYA_TX_SET_PROPERTY);");
        c.line("    kaya_wire_u64(tx, widget_id);");
        c.line(&format!("    kaya_wire_u32(tx, KAYA_PROP_{up});"));
        c.line("    kaya_wire_u32(tx, KAYA_SOURCE_CONST);");
        c.line(&format!("    kaya_wire_value(tx, {ctor}({param}));"));
        c.line("    kaya_wire_end(tx, kaya_at);");
        c.line("}");
        c.line("");
        c.line(&format!("/* set_property with a signal-bound {prop} value. */"));
        c.line(&format!("static inline void kaya_tx_bind_{prop}(KayaTx *tx, uint64_t widget_id, uint64_t signal_id) {{"));
        c.line("    size_t kaya_at = kaya_wire_begin(tx, KAYA_TX_SET_PROPERTY);");
        c.line("    kaya_wire_u64(tx, widget_id);");
        c.line(&format!("    kaya_wire_u32(tx, KAYA_PROP_{up});"));
        c.line("    kaya_wire_u32(tx, KAYA_SOURCE_SIGNAL);");
        c.line("    kaya_wire_u64(tx, signal_id);");
        c.line("    kaya_wire_end(tx, kaya_at);");
        c.line("}");
        c.line("");
        c.line("/* set_property bound to one field of the element of the enclosing");
        c.line(" * For, `level` Fors up (field 0 for a scalar collection). */");
        c.line(&format!("static inline void kaya_tx_bind_{prop}_element(KayaTx *tx, uint64_t widget_id, uint32_t level, uint32_t field) {{"));
        c.line("    size_t kaya_at = kaya_wire_begin(tx, KAYA_TX_SET_PROPERTY);");
        c.line("    kaya_wire_u64(tx, widget_id);");
        c.line(&format!("    kaya_wire_u32(tx, KAYA_PROP_{up});"));
        c.line("    kaya_wire_u32(tx, KAYA_SOURCE_ELEMENT);");
        c.line("    kaya_wire_u32(tx, level);");
        c.line("    kaya_wire_u32(tx, field);");
        c.line("    kaya_wire_end(tx, kaya_at);");
        c.line("}");
    }

    // Signal binders only for the bindable props (SOURCE_SIGNAL on the
    // rest dies at the root). The C floor is the ONE surface with no
    // shortcut canonicalizer, BY DESIGN: it writes the canonical wire
    // spelling itself and the core validates (DESIGN.md, Menus).
    for (prop, _, kind) in crate::menu_prop_variants(spec) {
        let up = prop.to_uppercase();
        let (ty, ctor, param) = match kind {
            crate::PropKind::Str => ("const char *", "kaya_str", *prop),
            crate::PropKind::Bool => ("int ", "kaya_bool", *prop),
            crate::PropKind::F64 => ("double ", "kaya_f64", *prop),
            crate::PropKind::Blob => ("uint64_t ", "kaya_blob", "handle"),
            crate::PropKind::Enum(_) => ("int64_t ", "kaya_i64", *prop),
        };
        c.line("");
        if *prop == "shortcut" {
            c.line("/* set_menu_prop with a constant shortcut value. NO canonicalizer");
            c.line(" * exists at the C floor by design: write the canonical wire spelling");
            c.line(" * yourself — lowercase '+'-joined tokens, modifiers in primary,");
            c.line(" * shift, alt order, then exactly one key (a-z, 0-9, or the closed");
            c.line(" * named set), e.g. \"primary+shift+s\". The core REJECTS non-canonical");
            c.line(" * forms rather than rewriting them (DESIGN.md, Menus). */");
        } else {
            c.line(&format!("/* set_menu_prop with a constant {prop} value. */"));
        }
        c.line(&format!("static inline void kaya_tx_set_menu_{prop}(KayaTx *tx, uint64_t item, {ty}{param}) {{"));
        c.line("    size_t kaya_at = kaya_wire_begin(tx, KAYA_TX_SET_MENU_PROP);");
        c.line("    kaya_wire_u64(tx, item);");
        c.line(&format!("    kaya_wire_u32(tx, KAYA_MPROP_{up});"));
        c.line("    kaya_wire_u32(tx, KAYA_SOURCE_CONST);");
        c.line(&format!("    kaya_wire_value(tx, {ctor}({param}));"));
        c.line("    kaya_wire_end(tx, kaya_at);");
        c.line("}");
        if crate::menu_prop_bindable(prop) {
            c.line("");
            c.line(&format!("/* set_menu_prop with a signal-bound {prop} value. */"));
            c.line(&format!("static inline void kaya_tx_bind_menu_{prop}(KayaTx *tx, uint64_t item, uint64_t signal_id) {{"));
            c.line("    size_t kaya_at = kaya_wire_begin(tx, KAYA_TX_SET_MENU_PROP);");
            c.line("    kaya_wire_u64(tx, item);");
            c.line(&format!("    kaya_wire_u32(tx, KAYA_MPROP_{up});"));
            c.line("    kaya_wire_u32(tx, KAYA_SOURCE_SIGNAL);");
            c.line("    kaya_wire_u64(tx, signal_id);");
            c.line("    kaya_wire_end(tx, kaya_at);");
            c.line("}");
        }
    }
    c.line("");
    c.line("/* Decode one value at `at`; returns the next offset. */");
    c.line("static inline size_t kaya_parse_value(const uint8_t *buf, size_t at, KayaVal *out) {");
    c.line("    memcpy(&out->type, buf + at, 4);");
    c.line("    uint32_t len;");
    c.line("    memcpy(&len, buf + at + 4, 4);");
    c.line("    out->i = 0;");
    c.line("    out->f = 0;");
    c.line("    out->s = 0;");
    c.line("    out->s_len = 0;");
    c.line("    switch (out->type) {");
    c.line("    case KAYA_VALUE_BOOL:");
    c.line("        out->i = buf[at + 8];");
    c.line("        break;");
    c.line("    case KAYA_VALUE_I64:");
    c.line("    case KAYA_VALUE_BLOB:");
    c.line("        memcpy(&out->i, buf + at + 8, 8);");
    c.line("        break;");
    c.line("    case KAYA_VALUE_F64:");
    c.line("        memcpy(&out->f, buf + at + 8, 8);");
    c.line("        break;");
    c.line("    default:");
    c.line("        out->s = (const char *)(buf + at + 8);");
    c.line("        out->s_len = len;");
    c.line("    }");
    c.line("    return at + 8 + ((len + 7) & ~7u);");
    c.line("}");
    c.line("");
    c.line("/* Decode one occurrence record (header included). Returns 1 for a");
    c.line(" * click, filling id and up to max_keys of the copy's key path");
    c.line(" * (empty for a click on a guest-created widget); 0 otherwise. */");
    c.line("static inline int kaya_parse_click(const uint8_t *rec, uint64_t *id,");
    c.line("                                   KayaVal *keys, uint32_t max_keys,");
    c.line("                                   uint32_t *n_keys) {");
    c.line("    const KayaRecordButtonClicked *r = (const KayaRecordButtonClicked *)rec;");
    c.line("    if (r->header.kind != KAYA_OCCURRENCE_BUTTON_CLICKED)");
    c.line("        return 0;");
    c.line("    *id = r->id;");
    c.line("    *n_keys = r->path_len;");
    c.line("    size_t at = sizeof(KayaRecordButtonClicked);");
    c.line("    for (uint32_t k = 0; k < r->path_len && k < max_keys; k++)");
    c.line("        at = kaya_parse_value(rec, at, &keys[k]);");
    c.line("    return 1;");
    c.line("}");
    c.line("");
    // DERIVED from the record shapes, so a new click-shaped record
    // reaches the C floor with zero emitter edits. button_clicked keeps
    // its historic name, kaya_parse_click, above.
    for name in crate::click_shaped_occurrence_names(spec)
        .iter()
        .filter(|n| **n != "button_clicked")
    {
        let up = name.to_uppercase();
        let pad = " ".repeat(31 + name.len());
        c.line(&format!(
            "/* Decode a {name} occurrence: the click identity shape — id plus"
        ));
        c.line(" * path_len key-path values (a node-anchored context activation");
        c.line(" * carries the stamped copy's keys; path_len is 0 for a bar or");
        c.line(" * live-widget item). Returns 1 and fills the outputs, or 0 for");
        c.line(" * other kinds. */");
        c.line(&format!(
            "static inline int kaya_parse_{name}(const uint8_t *rec, uint64_t *id,"
        ));
        c.line(&format!("{pad}KayaVal *keys, uint32_t max_keys,"));
        c.line(&format!("{pad}uint32_t *n_keys) {{"));
        c.line("    const KayaRecordButtonClicked *r = (const KayaRecordButtonClicked *)rec;");
        c.line(&format!("    if (r->header.kind != KAYA_OCCURRENCE_{up})"));
        c.line("        return 0;");
        c.line("    *id = r->id;");
        c.line("    *n_keys = r->path_len;");
        c.line("    size_t at = sizeof(KayaRecordButtonClicked);");
        c.line("    for (uint32_t k = 0; k < r->path_len && k < max_keys; k++)");
        c.line("        at = kaya_parse_value(rec, at, &keys[k]);");
        c.line("    return 1;");
        c.line("}");
        c.line("");
    }
    // The click identity shape plus the named u32 the tag family's
    // third slot carries. Derived, like the branch above.
    for r in spec
        .occurrence
        .iter()
        .filter(|r| crate::u32_slot_occurrence_names(spec).contains(&r.name))
    {
        let name = r.name;
        let up = name.to_uppercase();
        let slot = r.fields[2].name;
        let pad = " ".repeat(31 + name.len());
        c.line(&format!(
            "/* Decode a {name} occurrence: id plus path_len key-path values,"
        ));
        c.line(&format!(
            " * plus `{slot}` from the slot the click family pads. Returns 1 and"
        ));
        c.line(" * fills the outputs, or 0 for other kinds. */");
        c.line(&format!(
            "static inline int kaya_parse_{name}(const uint8_t *rec, uint64_t *id,"
        ));
        c.line(&format!("{pad}KayaVal *keys, uint32_t max_keys,"));
        c.line(&format!("{pad}uint32_t *n_keys, uint32_t *{slot}) {{"));
        c.line("    const KayaRecordButtonClicked *r = (const KayaRecordButtonClicked *)rec;");
        c.line(&format!("    if (r->header.kind != KAYA_OCCURRENCE_{up})"));
        c.line("        return 0;");
        c.line("    *id = r->id;");
        c.line("    *n_keys = r->path_len;");
        c.line(&format!(
            "    memcpy({slot}, rec + 20, sizeof(uint32_t)); /* the click family's pad slot */"
        ));
        c.line("    size_t at = sizeof(KayaRecordButtonClicked);");
        c.line("    for (uint32_t k = 0; k < r->path_len && k < max_keys; k++)");
        c.line("        at = kaya_parse_value(rec, at, &keys[k]);");
        c.line("    return 1;");
        c.line("}");
        c.line("");
    }
    // From the spec's Record::payload, so the kind list cannot drift.
    for r in spec.occurrence.iter().filter(|r| r.payload.is_some()) {
        let name = r.name;
        let up = name.to_uppercase();
        let pad = " ".repeat(31 + name.len());
        c.line(&format!(
            "/* Decode a {name} occurrence: same identity head as a click, then"
        ));
        c.line(&format!(
            " * its payload as one {:?} value (strings point into rec). Returns 1",
            r.payload.unwrap()
        ));
        c.line(" * and fills the outputs, or 0 for other kinds. */");
        c.line(&format!(
            "static inline int kaya_parse_{name}(const uint8_t *rec, uint64_t *id,"
        ));
        c.line(&format!("{pad}KayaVal *keys, uint32_t max_keys,"));
        c.line(&format!("{pad}uint32_t *n_keys, KayaVal *payload) {{"));
        c.line("    const KayaRecordButtonClicked *r = (const KayaRecordButtonClicked *)rec;");
        c.line(&format!("    if (r->header.kind != KAYA_OCCURRENCE_{up})"));
        c.line("        return 0;");
        c.line("    *id = r->id;");
        c.line("    *n_keys = r->path_len;");
        c.line("    size_t at = sizeof(KayaRecordButtonClicked);");
        c.line("    for (uint32_t k = 0; k < r->path_len && k < max_keys; k++)");
        c.line("        at = kaya_parse_value(rec, at, &keys[k]);");
        c.line("    kaya_parse_value(rec, at, payload);");
        c.line("    return 1;");
        c.line("}");
        c.line("");
    }
    // The canvas asks: a click identity shape, then BARE values with no
    // count in front of them, read until the record ends
    // (docs/canvas-plan.md §3.2.1). Derived, like the branches above.
    for name in crate::values_tail_occurrence_names(spec) {
        let up = name.to_uppercase();
        let pad = " ".repeat(31 + name.len());
        c.line(&format!(
            "/* Decode a {name} occurrence: id plus path_len key-path values,"
        ));
        c.line(" * then the trailing run of bare values (width and height in");
        c.line(" * points, and a tick's frame time in seconds) — read to the end");
        c.line(" * of the record, since the run carries no count. Returns 1 and");
        c.line(" * fills the outputs, or 0 for other kinds. */");
        c.line(&format!(
            "static inline int kaya_parse_{name}(const uint8_t *rec, uint64_t *id,"
        ));
        c.line(&format!("{pad}KayaVal *keys, uint32_t max_keys,"));
        c.line(&format!("{pad}uint32_t *n_keys, KayaVal *vals,"));
        c.line(&format!("{pad}uint32_t max_vals, uint32_t *n_vals) {{"));
        c.line("    const KayaRecordButtonClicked *r = (const KayaRecordButtonClicked *)rec;");
        c.line(&format!("    if (r->header.kind != KAYA_OCCURRENCE_{up})"));
        c.line("        return 0;");
        c.line("    *id = r->id;");
        c.line("    *n_keys = r->path_len;");
        c.line("    *n_vals = 0;");
        c.line("    size_t at = sizeof(KayaRecordButtonClicked);");
        c.line("    for (uint32_t k = 0; k < r->path_len; k++) {");
        c.line("        KayaVal scratch;");
        c.line("        at = kaya_parse_value(rec, at, k < max_keys ? &keys[k] : &scratch);");
        c.line("    }");
        c.line("    while (at < r->header.size) {");
        c.line("        KayaVal scratch;");
        c.line("        int room = *n_vals < max_vals;");
        c.line("        at = kaya_parse_value(rec, at, room ? &vals[*n_vals] : &scratch);");
        c.line("        (*n_vals)++;");
        c.line("    }");
        c.line("    return 1;");
        c.line("}");
        c.line("");
    }
    c.line("#endif /* KAYA_WIRE_H */");
    c.out
}
