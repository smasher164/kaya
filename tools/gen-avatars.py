#!/usr/bin/env python3
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "lib"))
from kaya_gate import ROOT, dev_shell_or_die, scratch_dir

dev_shell_or_die()

# The chat app's conversation pictures (guests/assets/avatars/README.md):
# abstract, no faces. FFmpeg is the dev shell's; byte-stable with +bitexact
# and one thread.
#
#   tools/gen-avatars.py                  write guests/assets/avatars/
#   tools/gen-avatars.py --out DIR        write DIR instead
#   tools/gen-avatars.py --check [--against DIR]
#                                         regenerate into scratch and compare

import argparse
import subprocess

FAMILY = ROOT / "guests" / "assets" / "avatars"
SIDE = 160

INSIDE = {
    "sun": "lt(hypot(X-W/2,Y-H*0.6),W*0.22)",
    "diamond": "lt(abs(X-W/2)+abs(Y-H/2),W*0.27)",
    "peak": "gt(Y,H*0.28+abs(X-W/2)*1.15)*lt(Y,H*0.74)",
}

# name, gradient top RGB, gradient bottom RGB, motif, motif RGB
AVATARS = [
    ("maya.jpg", (0xF2, 0x99, 0x4A), (0xD9, 0x48, 0x6A), "sun", (0xFF, 0xE8, 0xC2)),
    ("sam.jpg", (0x2B, 0xB3, 0xA3), (0x1D, 0x6F, 0x8C), "diamond", (0xE6, 0xF7, 0xF2)),
    ("alex.jpg", (0x8E, 0x6F, 0xE0), (0x4A, 0x3A, 0xA8), "peak", (0xEE, 0xE8, 0xFF)),
]


def channel(i, top, bottom, motif, ink):
    grad = f"{top[i]}+({bottom[i] - top[i]})*Y/H"
    return f"if({INSIDE[motif]},{ink[i]},{grad})"


def generate(out):
    out.mkdir(parents=True, exist_ok=True)
    for name, top, bottom, motif, ink in AVATARS:
        geq = ":".join(f"{c}='{channel(i, top, bottom, motif, ink)}'"
                       for i, c in enumerate("rgb"))
        cmd = ["ffmpeg", "-nostdin", "-hide_banner", "-loglevel", "error", "-y",
               "-threads", "1", "-filter_threads", "1",
               "-f", "lavfi", "-i", f"color=c=black:s={SIDE}x{SIDE}:d=1",
               "-vf", f"format=gbrp,geq={geq},format=yuvj420p",
               "-frames:v", "1", "-c:v", "mjpeg", "-q:v", "3",
               "-fflags", "+bitexact", "-flags", "+bitexact",
               "-map_metadata", "-1", str(out / name)]
        r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                           check=False)
        if r.returncode != 0:
            raise SystemExit(f"gen-avatars: ffmpeg failed on {name}: {r.stderr.strip()}")


def listing(d):
    return {p.name: p.read_bytes() for p in sorted(d.glob("*.jpg"))}


def compare(fresh, committed):
    a, b = listing(fresh), listing(committed)
    bad = [f"{n}: not generated by tools/gen-avatars.py" for n in sorted(set(b) - set(a))]
    bad += [f"{n}: generated but not in {committed}" for n in sorted(set(a) - set(b))]
    bad += [f"{n}: differs from what tools/gen-avatars.py generates"
            for n in sorted(set(a) & set(b)) if a[n] != b[n]]
    return bad, len(a)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=pathlib.Path)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--against", type=pathlib.Path, default=FAMILY)
    args = ap.parse_args()
    if args.check:
        with scratch_dir("kaya-gen-avatars-") as fresh:
            generate(fresh)
            bad, n = compare(fresh, args.against)
        if bad:
            for b in bad:
                print(f"gen-avatars: {b}", file=sys.stderr)
            print(f"gen-avatars: FAIL — {len(bad)} of {n} files; regenerate with "
                  f"`tools/gen-avatars.py`", file=sys.stderr)
            raise SystemExit(1)
        print(f"gen-avatars: OK — {n} files byte-identical to {args.against}")
        return
    out = args.out or FAMILY
    for p in out.glob("*.jpg"):
        p.unlink()
    generate(out)
    for name, data in listing(out).items():
        print(f"gen-avatars: wrote {name}, {len(data)} bytes")


main()
