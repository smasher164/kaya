#!/usr/bin/env bash

kaya_flake="$(cd "$(dirname "$0")/../.." && cat flake.nix flake.lock | shasum -a 256 | cut -c1-12)"
if [ "${KAYA_DEV_SHELL:-}" != "$kaya_flake" ]; then
    if [ -z "${KAYA_DEV_SHELL:-}" ]; then
        echo "$0: not inside the dev shell — run this under \`nix develop\`" >&2
    else
        echo "$0: dev shell is stale — the flake changed since it was entered; re-enter \`nix develop\`" >&2
    fi
    exit 1
fi
# Build the SwiftUI backend dylib (macOS): the Swift presentation layer
# plus the kaya_swiftui_run C entry. `--release` builds the optimized pair a
# shipped bundle carries (tools/lib/packaging/mac.py) into target/swiftui-release
# and target/release; the lanes run the unoptimized pair (docs/traps.md, the
# mac app's interaction latency).
set -euo pipefail

PROFILE=debug
SWIFT_OPT=-Onone
SWIFT_DIR=target/swiftui
CARGO_PROFILE=()
case "${1:-}" in
    "") ;;
    --release)
        PROFILE=release
        SWIFT_OPT=-O
        SWIFT_DIR=target/swiftui-release
        CARGO_PROFILE=(--release)
        ;;
    *)
        echo "usage: $0 [--release]" >&2
        exit 2
        ;;
esac

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"

# shellcheck source=tools/lib/swift-toolchain.sh
source "$ROOT/tools/lib/swift-toolchain.sh"

cargo build --locked --lib "${CARGO_PROFILE[@]}"
# The Swift dylib below compiles against this library's header and loads
# it at run time; both must come from one tree.
tools/build-id.py --verify "${CARGO_TARGET_DIR:-target}/$PROFILE/libkaya.dylib"
tools/gen-header.py --check

# The interpreter carries the id of the sources it was compiled from
# (tools/build-id.py): a separate artifact from a separate toolchain, so
# it goes stale separately.
#
# A `public let` survives -O into the dylib's string table (measured
# against a plain let, an @_cdecl and a byte array — all four survive,
# this is the least machinery).
mkdir -p "$SWIFT_DIR"
# ONE BUILDER AT A TIME: the matrix's gate sweep and the mac lane's
# skip path (tools/validate-all.py, 2026-08-20) can both reach here in
# the same second, and two concurrent swiftc runs write one dylib —
# cargo has its own lock, this artifact needs one of its own. mkdir is
# the atomic primitive; a crashed holder's lock dies with the deadline.
LOCK=$SWIFT_DIR/.build-lock
waited=0
until mkdir "$LOCK" 2>/dev/null; do
    waited=$((waited + 1))
    if [ "$waited" -gt 300 ]; then
        echo "build-dylib: the build lock $LOCK is stuck after 300s — a dead" >&2
        echo "  builder left it; remove the directory and rerun." >&2
        exit 1
    fi
    sleep 1
done
trap 'rmdir "$LOCK" 2>/dev/null' EXIT
KAYA_SWIFTUI_ID="$(tools/build-id.py swiftui)"
MARKER_SWIFT=$SWIFT_DIR/KayaBuildId.swift
# The opt-level marker is written from the flag swiftc is handed below, so
# the two cannot disagree (tools/build-id.py --optimized reads it). Over 15
# bytes, or Swift stores it as an immediate small string and no byte scan
# finds it.
SWIFT_OPT_MARK=0
[ "$SWIFT_OPT" = "-Onone" ] || SWIFT_OPT_MARK=O
cat >"$MARKER_SWIFT" <<EOF
// Generated by tools/swiftui/build-dylib.sh. Do not edit, do not commit.
public let kayaSwiftUIBuildIdMarker = "kaya-build-id:$KAYA_SWIFTUI_ID"
public let kayaSwiftUIOptMarker = "kaya-opt:$SWIFT_OPT_MARK swiftc $SWIFT_OPT"
EOF

OUT=$SWIFT_DIR/libkaya_swiftui.dylib

# ALREADY FRESH MEANS DONE: when the dylib in place carries this tree's
# own id, a rebuild would produce the same thing — and the matrix's
# concurrent shape (tools/validate-all.py, 2026-08-20) has the gate
# sweep and the mac lane both arriving here while legs are dlopening
# the artifact, so a needless rebuild is not merely slow.
optimized_as_asked() {
    if tools/build-id.py --optimized "$OUT" >/dev/null 2>&1; then
        [ "$PROFILE" = release ]
    else
        [ "$PROFILE" = debug ]
    fi
}
if [ -f "$OUT" ] \
    && tools/build-id.py --verify --component swiftui "$OUT" >/dev/null 2>&1 \
    && optimized_as_asked; then
    echo "built $OUT (already carries this tree's id)"
    exit 0
fi

# A FAILED BUILD MUST NOT LEAVE A USABLE ARTIFACT (docs/traps.md):
# compile to a scratch path, then REPLACE atomically on success — legs
# dlopen this path while a concurrent sweep rebuilds, and a delete-first
# shape left a ~30s hole that killed eight legs (2026-08-20). On FAILURE
# the old dylib is deleted.
#
# -warnings-as-errors is a GUARD: a dropped return value is only a
# warning, and that is how a clipboard seed discarded osascript's exit
# status for the life of the scene (docs/traps.md).
if ! kaya_swiftc \
    -warnings-as-errors \
    "$SWIFT_OPT" \
    -emit-library \
    -import-objc-header crates/kaya/include/kaya.h \
    swift/KayaSwiftUI.swift swift/KayaSwiftUIEntry.swift "$MARKER_SWIFT" \
    -Xlinker -undefined -Xlinker dynamic_lookup \
    -framework AppKit -framework Foundation \
    -o "$OUT.tmp"; then
    rm -f "$OUT.tmp" "$OUT"
    echo "build-dylib: FAILED — no dylib left in place (a stale one would be tested silently)" >&2
    exit 1
fi
mv -f "$OUT.tmp" "$OUT"
# The dylib in place must be the one this run compiled.
tools/build-id.py --verify --component swiftui "$OUT"
if [ "$PROFILE" = release ] \
    && ! tools/build-id.py --optimized "$OUT" "${CARGO_TARGET_DIR:-target}/release/libkaya.dylib"; then
    rm -f "$OUT"
    echo "build-dylib: FAILED — the release pair is not optimized; no dylib left in place" >&2
    exit 1
fi
echo "built $OUT"
