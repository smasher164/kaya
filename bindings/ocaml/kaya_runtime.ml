(* kaya runtime for OCaml guests: loading, the direct-ring occurrence
   loop, and submit. Hand-written; the wire vocabulary next to it
   (kaya_wire.ml) is generated by kaya-bindgen, and kaya_ml_stubs.c
   carries the two ordered cursor accesses.

   The direct tier, the way ocaml-uring binds the real io_uring: a
   Bigarray wraps the ring's memory so record parsing compiles to inline
   loads — no FFI, byte-wise through the char kind so nothing boxes —
   while the head/tail cursors go through noalloc C stubs (OCaml's
   Atomic covers OCaml-heap cells only). Blocking calls are bound with
   ~release_runtime_lock so the runtime keeps scheduling while C blocks.

   Build (with the stubs and the generated module):
       ocamlfind ocamlopt -package ctypes,ctypes-foreign,threads.posix \
           -linkpkg kaya_ml_stubs.c kaya_wire.ml kaya_runtime.ml app.ml *)

open Ctypes
open Foreign

let library_path () =
  match Sys.getenv_opt "KAYA_LIB" with
  | Some lib -> lib
  | None ->
      let candidates =
        [ "target/debug/libkaya.dylib"; "target/debug/libkaya.so" ]
      in
      (try List.find Sys.file_exists candidates
       with Not_found ->
         failwith "libkaya not found; build with cargo or set KAYA_LIB")

let lib = Dl.dlopen ~filename:(library_path ()) ~flags:[ Dl.RTLD_NOW ]

(* KayaRingInfo, as declared in kaya.h. *)
type ring_info
let ring_info : ring_info structure typ = structure "KayaRingInfo"
let ri_data = field ring_info "data" (ptr uint8_t)
let ri_capacity = field ring_info "capacity" uint32_t
let ri_head = field ring_info "head" (ptr uint32_t)
let ri_tail = field ring_info "tail" (ptr uint32_t)
let () = seal ring_info

let kaya_run =
  foreign ~from:lib ~release_runtime_lock:true "kaya_run"
    (void @-> returning int32_t)

let kaya_occurrence_ring =
  foreign ~from:lib "kaya_occurrence_ring" (ptr ring_info @-> returning void)

let kaya_wait_occurrences =
  foreign ~from:lib ~release_runtime_lock:true "kaya_wait_occurrences"
    (void @-> returning bool)

let kaya_wake = foreign ~from:lib "kaya_wake" (void @-> returning void)

(* Return the app thread from wait_occurrences. Safe from any thread;
   the binding calls it from Kaya_app.post, and guests do not name it. *)
let wake () = kaya_wake ()

(* Block until there MAY be something to do: a record arrived, or
   another thread called wake. false once the core has shut down.
   "May" is the honest word — a wake returns true with the ring still
   empty, and the caller re-checks both sources, which a
   drain-then-poll loop does anyway. *)
let wait_occurrences () = kaya_wait_occurrences ()

let kaya_submit =
  foreign ~from:lib "kaya_submit" (string @-> size_t @-> returning void)

let kaya_blob_register =
  foreign ~from:lib "kaya_blob_register"
    (string @-> size_t @-> returning uint64_t)

let kaya_occurrence_blob =
  foreign ~from:lib "kaya_occurrence_blob"
    (uint64_t @-> ptr size_t @-> returning (ptr char))

let kaya_occurrence_blob_release =
  foreign ~from:lib "kaya_occurrence_blob_release" (uint64_t @-> returning void)

(* Redeem an occurrence blob for its bytes, and release it. Installed
   into the generated wire module, which opens no library of its own.

   COPY THEN RELEASE, in that order: the pointer borrows core memory
   that the release frees. A blob arriving in an OCCURRENCE is a handle
   into a table with no boundary that retires one — unlike the apply
   channel's batch-local index, which the next batch supersedes — so the
   decoder is what has to let go of it, while decoding, before any
   handle can reach an app. *)
let occurrence_blob handle =
  let len = allocate size_t (Unsigned.Size_t.of_int 0) in
  let data = kaya_occurrence_blob (Unsigned.UInt64.of_int64 handle) len in
  let n = Unsigned.Size_t.to_int !@len in
  let out =
    if is_null data || n = 0 then ""
    else String.init n (fun i -> !@(data +@ i))
  in
  kaya_occurrence_blob_release (Unsigned.UInt64.of_int64 handle);
  out

let () = Kaya_wire.occurrence_blob := occurrence_blob

let kaya_open_picked =
  foreign ~from:lib ~release_runtime_lock:true "kaya_open_picked"
    (uint64_t @-> uint32_t @-> ptr int64_t @-> ptr uint32_t @-> returning int32_t)

(* Redeem a picked handle for a real Unix.file_descr, plus whether it
   seeks.

   BLOCKS, and may block for a long time — a cloud provider can
   download the file before it answers — so call it from a thread you
   chose and post the result back (DESIGN.md, File dialogs). The
   runtime lock is released for the duration, so the rest of the
   program keeps running.

   THE DESCRIPTOR BECOMES OCAML'S: [Unix.file_descr] IS the integer on
   POSIX, so this is a representation change and not a copy, and
   [Unix.close] closes it exactly once. The core keeps no claim. *)
let open_picked handle mode =
  let raw = Ctypes.allocate Ctypes.int64_t 0L in
  let seekable = Ctypes.allocate Ctypes.uint32_t Unsigned.UInt32.zero in
  let rc =
    kaya_open_picked
      (Unsigned.UInt64.of_int64 handle)
      (Unsigned.UInt32.of_int mode)
      raw seekable
  in
  if rc <> 0l then
    failwith
      (Printf.sprintf "kaya: opening the picked file failed (code %ld)" rc);
  let fd : Unix.file_descr =
    Obj.magic (Int64.to_int (Ctypes.( !@ ) raw))
  in
  (fd, Unsigned.UInt32.to_int (Ctypes.( !@ ) seekable) <> 0)

(* The ordered cursor accesses; see kaya_ml_stubs.c. *)
external load_acquire_u32 : nativeint -> int = "kaya_ml_load_acquire_u32"
  [@@noalloc]
external store_release_u32 : nativeint -> int -> unit
  = "kaya_ml_store_release_u32"
  [@@noalloc]

(* Enter the core on the calling thread (which must be the process main
   thread); returns the exit code when the app ends. *)
(* ~from:lib like every other binding: the default handle is the
   process image, which finds dlopened symbols on macOS but not on
   Linux — exactly the kind of platform split the guard exists for. *)
let kaya_spec_hash = foreign ~from:lib "kaya_spec_hash" (void @-> returning int64_t)

(* The stale-artifact guard: this binding was generated from one spec
   revision; the loaded library must speak the same one. *)
let check_spec () =
  let got = kaya_spec_hash () in
  if got <> Kaya_wire.spec_hash then
    failwith
      (Printf.sprintf
         "kaya: library speaks spec %Lx, this binding was generated from %Lx — \
          rebuild the library or regenerate bindings"
         got Kaya_wire.spec_hash)

let run () =
  check_spec ();
  Int32.to_int (kaya_run ())

(* Submit one transaction: the concatenation of packed records (tx_*
   results from Kaya_wire), applied atomically. *)
let submit records =
  let tx = String.concat "" records in
  kaya_submit tx (Unsigned.Size_t.of_int (String.length tx))

(* Register bulk payload bytes (an encoded image) with the core: one
   copy into core-owned memory, returning the handle (a u64, carried
   as the int64 the Blob wire value takes). The handle is consumed by
   the next submit from this guest, referenced or not; the caller's
   bytes are free to drop the moment this returns. *)
let register_blob data =
  let s = Bytes.to_string data in
  Unsigned.UInt64.to_int64
    (kaya_blob_register s (Unsigned.Size_t.of_int (String.length s)))

(* Block for the next occurrence; None when the core has shut down.
   Some (kind, id, keys, payload, clip, undo): keys are [] when the id
   is a widget id, else the id is a template node id and the keys are
   the stamped copy's key path, outermost first; payload is Some for
   text_changed (a Str), toggled (a Bool) and value_changed (an F64),
   plus the two menu kinds that carry the same three
   ([Kaya_wire.parse_occurrence] decides, and it is generated); undo is
   the raw body of an undone/redone record — the one payload with no
   slot of its own (see the scan below). *)
(* Read the next occurrence if one is ready, WITHOUT blocking; None
   means the ring is empty right now.

   Polling and waiting are separate calls, rather than one blocking
   next_occurrence, because the app thread has a SECOND source of work:
   closures posted from other threads. A single blocking read would park
   inside C with no way back out to drain them. *)
let poll_occurrence =
  let state = ref None in
  fun () ->
    let data, mask, head_addr, tail_addr, h =
      match !state with
      | Some s -> s
      | None ->
          let info = make ring_info in
          kaya_occurrence_ring (addr info);
          let capacity = Unsigned.UInt32.to_int (getf info ri_capacity) in
          let data =
            bigarray_of_ptr array1 capacity Bigarray.char
              (coerce (ptr uint8_t) (ptr char) (getf info ri_data))
          in
          let head_addr = raw_address_of_ptr (to_voidp (getf info ri_head)) in
          let tail_addr = raw_address_of_ptr (to_voidp (getf info ri_tail)) in
          let s =
            (data, capacity - 1, head_addr, tail_addr,
             ref (load_acquire_u32 head_addr))
          in
          state := Some s;
          s
    in
    let byte i = Char.code (Bigarray.Array1.get data i) in
    let rec scan () =
      let t = load_acquire_u32 tail_addr in (* acquire: records visible *)
      if !h = t then None (* nothing ready; the caller waits *)
      else begin
        let at = !h land mask in
        let size = Kaya_wire.u32_at byte at in
        let kind = Kaya_wire.u16_at byte (at + 4) in
        (* AN UNDO STEP CANNOT RIDE THE SHARED TUPLE, so it travels as
           its own bytes and Kaya_app cuts it up.
           [parse_occurrence]'s slots are {id, keys, payload, clip}, and
           an undone/redone carries a window, four run lengths, a label
           and one flat delta tail — nothing that fits. Worse, the
           generic tail it would fall through to reads {u64 id, u32
           path_len}, which takes `window` for a widget and the SIGNAL
           COUNT for a key-path length, then reads the label's bytes as
           keys: junk, silently. So these two kinds never reach it.
           The body is copied out of the ring HERE because the space is
           handed back three lines below — a record does not wrap (the
           writer pads), so the copy is one contiguous run. *)
        let undo =
          if kind = Kaya_wire.occ_kind_undone || kind = Kaya_wire.occ_kind_redone
          then Some (String.init (size - 8) (fun i -> Char.chr (byte (at + 8 + i))))
          else None
        in
        let parsed =
          match undo with
          (* The window rides where every other record's id does, and it
             is what keys the per-window handler. *)
          | Some _ ->
              Some (kind, Int64.of_int (Kaya_wire.u32_at byte (at + 8)), [], None, None)
          | None -> Kaya_wire.parse_occurrence (fun i -> byte (at + i))
        in
        (* The cursors are u32 and wrap; OCaml ints are wider, so wrap by
           hand before handing the space back with a release store. *)
        h := (!h + size) land 0xFFFFFFFF;
        store_release_u32 head_addr !h;
        match parsed with
        | Some (kind, id, keys, payload, clip) ->
            Some (kind, id, keys, payload, clip, undo)
        | None -> scan ()
      end
    in
    scan ()
