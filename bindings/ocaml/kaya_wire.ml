(* Reads assembled from a byte accessor (absolute offset -> byte);
   kaya v1 targets are all little-endian. *)
let u16_at byte i = byte i lor (byte (i + 1) lsl 8)
let u32_at byte i = u16_at byte i lor (u16_at byte (i + 2) lsl 16)

(* Decode one value at offset [at]; returns (value, next offset). *)
let parse_value byte at =
  let vtype = u32_at byte at in
  let vlen = u32_at byte (at + 4) in
  let next = at + 8 + ((vlen + 7) land lnot 7) in
  let v =
    if vtype = value_bool then Bool (byte (at + 8) <> 0)
    else if vtype = value_i64 || vtype = value_f64 || vtype = value_blob
    then begin
      let n = ref 0L in
      for i = 7 downto 0 do
        n := Int64.logor (Int64.shift_left !n 8)
               (Int64.of_int (byte (at + 8 + i)))
      done;
      if vtype = value_i64 then I64 !n
      else if vtype = value_blob then Blob !n
      else F64 (Int64.float_of_bits !n)
    end
    else Str (String.init vlen (fun i -> Char.chr (byte (at + 8 + i))))
  in
  (v, next)

(* Redeem-and-release for occurrence blobs, installed by the runtime
   at load (this module opens no library of its own). *)
let occurrence_blob : (int64 -> string) ref =
  ref (fun _ -> failwith "kaya: no occurrence-blob redeemer installed")

(* Decode one representation at [at]: the clip kind, then its values.
   Blobs are redeemed to their bytes and RELEASED here, so no handle
   ever reaches an app. The kind is a SINGLE member of the clip enum
   and never a mask (you offer many and you receive one); 0 with no
   values is the universal empty answer. *)
let parse_clip byte at =
  let clip = u32_at byte at in
  let count = u32_at byte (at + 8) in
  let at = ref (at + 16) in
  let out = ref [] in
  for _ = 1 to count do
    let v, next = parse_value byte !at in
    let v = match v with Blob h -> Str (!occurrence_blob h) | v -> v in
    out := v :: !out;
    at := next
  done;
  (clip, List.rev !out, !at)

(* Decode one occurrence record (header included) through the byte
   accessor. Some (kind, id, keys, payload) — keys is [] when id is
   a widget id, else id is a template node id and keys is the copy's
   key path; payload is Some for text_changed/toggled/value_changed
   (a Str, Bool, or F64
   value), None for clicks. None for pad/unknown kinds. *)
let parse_occurrence byte =
  let kind = u16_at byte 4 in
  if kind <> occ_kind_button_clicked && kind <> occ_kind_text_changed && kind <> occ_kind_toggled && kind <> occ_kind_value_changed && kind <> occ_kind_close_requested && kind <> occ_kind_window_closed && kind <> occ_kind_alert_result && kind <> occ_kind_entry_popped && kind <> occ_kind_back_requested && kind <> occ_kind_section_selected && kind <> occ_kind_menu_activated && kind <> occ_kind_menu_toggled && kind <> occ_kind_menu_value_changed && kind <> occ_kind_file_dialog_result && kind <> occ_kind_clipboard_result && kind <> occ_kind_pasted && kind <> occ_kind_undone && kind <> occ_kind_redone && kind <> occ_kind_sort_requested && kind <> occ_kind_draw_requested && kind <> occ_kind_tick then None
  else begin
    (* ids are guest-allocated and small; the low u32 is the story. *)
    let id = u32_at byte 8 in
    if kind = occ_kind_alert_result
    then
      (* The alert's one answer: id + u32 choice (the alert_choice values). *)
      Some (kind, Int64.of_int id, [], Some (I64 (Int64.of_int (u32_at byte 16))), None, [])
    else if kind = occ_kind_file_dialog_result
    then begin
      (* id, a count, then three Values per file (handle, name,
         local_path), FLATTENED into the values slot; the app
         layer regroups them. EMPTY IS CANCEL. *)
      let count = u32_at byte 16 in
      let at = ref 32 in
      let out = ref [] in
      for _ = 1 to count * 3 do
        let v, next = parse_value byte !at in
        out := v :: !out;
        at := next
      done;
      Some (kind, Int64.of_int id, List.rev !out, None, None, [])
    end
    else if kind = occ_kind_clipboard_result
    then begin
      let clip, values, _ = parse_clip byte 16 in
      Some (kind, Int64.of_int id, [], None, Some (clip, values), [])
    end
    (* Surface lifecycle records carry the surface id alone
       ( derived from the record shapes ). *)
    else if kind = occ_kind_close_requested || kind = occ_kind_window_closed || kind = occ_kind_entry_popped || kind = occ_kind_back_requested
    then Some (kind, Int64.of_int id, [], None, None, [])
    (* Surface-pair records (window, section): the SECOND id
       keys the handler; the first rides as the payload. *)
    else if kind = occ_kind_section_selected
    then
      Some
        ( kind,
          Int64.of_int (u32_at byte 16),
          [],
          Some (I64 (Int64.of_int id)),
          None,
          [] )
    else begin
    let path_len = u32_at byte 16 in
    let keys = ref [] in
    let at = ref 24 in
    for _ = 1 to path_len do
      let v, next = parse_value byte !at in
      keys := v :: !keys;
      at := next
    done;
    let payload =
      if kind = occ_kind_sort_requested then
        Some (I64 (Int64.of_int (u32_at byte 20)))
      else
      if kind = occ_kind_text_changed || kind = occ_kind_toggled || kind = occ_kind_value_changed || kind = occ_kind_menu_toggled || kind = occ_kind_menu_value_changed then
        Some (fst (parse_value byte !at))
      else None
    in
    let clip =
      if kind = occ_kind_pasted then
        let clip, values, _ = parse_clip byte !at in
        Some (clip, values)
      else None
    in
    let tail =
      if kind = occ_kind_draw_requested || kind = occ_kind_tick then begin
        (* The canvas asks carry a run of BARE values after the
           key path — the assigned size, and a tick's frame time
           — with no count in front, so they are read until the
           record ends (docs/canvas-plan.md §3.2.1). *)
        let stop = u32_at byte 0 in
        let out = ref [] in
        while !at < stop do
          let v, next = parse_value byte !at in
          out := v :: !out;
          at := next
        done;
        List.rev !out
      end
      else []
    in
    Some (kind, Int64.of_int id, List.rev !keys, payload, clip, tail)
    end
  end
